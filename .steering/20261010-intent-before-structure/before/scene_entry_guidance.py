"""Shared authoring guidance; not an additional schema or quality gate."""

SCENE_ENTRY_GUIDANCE = (
    "Design scene entries and emotional progression before detailing individual shots. "
    "Compare the previous scene's shown ending with what this scene assumes the audience knows. "
    "For a newly shown place, time, participant or relationship, provide enough source-grounded "
    "orientation to understand where we are, whose viewpoint matters, why they are here and how "
    "the encounter begins before demanding an emotional response. Use an appropriate arrival, "
    "threshold, spatial relation, gaze, greeting or contextual cue; a wide exterior, travel shot "
    "or verbal introduction is not mandatory. An asset's existence is not evidence that the "
    "audience has already met its subject. Preserve intentional mystery and reveal order. "
    "Use ki-sho-ten-ketsu as functions of orientation, developing expectation, a meaningful "
    "event/change or deepening, and consequence/reaction/aftertaste leading onward. These are "
    "not four required shots, four new events, or a mandatory twist or happy resolution. "
    "Connect these local functions to the whole story's emotional arc: let anticipation, "
    "choices and observable responses earn the intended feeling rather than assuming that "
    "a spectacle or an emotion label alone creates it. Do not promise experienced emotion. "
    "Keep economical ellipses when location, participants and cause remain understandable; "
    "do not replay every journey or repeat introductions for known subjects. "
    "Use existing scene intent, start/end states, audience knowledge, ordered source beats "
    "and handoffs; during cut design use existing direction, purpose, continuity, performance "
    "and timing fields. Place staging within its owned source beat and distinguish directorial "
    "presentation from source facts. Do not invent travel methods, encounters, motives or "
    "revelations to fill the structure, reorder adopted events, or require new schema fields. "
    "For an existing fixed timeline, do not silently lengthen, shorten or regenerate narration "
    "to add an introduction. Preserve approved media unless the user requests its revision."
)
